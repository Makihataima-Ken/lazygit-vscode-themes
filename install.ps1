    # For config text read by Read-ConfigText: the encoding's name if it is UTF-16 or UTF-32
    # (a byte order mark, or NUL bytes), else ''. Windows PowerShell 5.1's > and Out-File write
    # UTF-16LE. Such a file cannot be edited byte-wise: the theme block is UTF-8.
    function Get-WideEncodingName([string]$Text) {
        $nul = [string][char]0
        if ($Text.StartsWith([string][char]0xFF + [char]0xFE + $nul + $nul, [System.StringComparison]::Ordinal)) { return 'UTF-32LE' }
        if ($Text.StartsWith($nul + $nul + [char]0xFE + [char]0xFF, [System.StringComparison]::Ordinal)) { return 'UTF-32BE' }
        if ($Text.StartsWith([string][char]0xFF + [char]0xFE, [System.StringComparison]::Ordinal)) { return 'UTF-16LE' }
        if ($Text.StartsWith([string][char]0xFE + [char]0xFF, [System.StringComparison]::Ordinal)) { return 'UTF-16BE' }
        if ($Text.Contains($nul)) { return 'UTF-16 or UTF-32 (it contains NUL bytes)' }
        return ''
    }

    # Config text for key checks only (never written back); UTF-16/UTF-32 is decoded by its BOM.
    function Read-ConfigScanText([string]$Path) {
        $text = Read-ConfigText $Path
        if (Get-WideEncodingName $text) { return [System.IO.File]::ReadAllText($Path) }
        return $text
    }

    # A PowerShell single-quoted string literal (also doubles the typographic quotes).
    function ConvertTo-QuotedArgument([string]$Text) {
        return "'" + [System.Management.Automation.Language.CodeGeneration]::EscapeSingleQuotedStringContent($Text) + "'"
    }

    # LF line endings, no BOM, exactly one trailing newline.
    function ConvertTo-ThemeText([string]$Text) {
        $t = $Text -replace "`r`n", "`n"
        if ($t.Length -gt 0 -and $t[0] -eq [char]0xFEFF) { $t = $t.Substring(1) }
        $t = $t -replace "`n+\z", ''
        return $t + "`n"
    }

    function Resolve-FullPath([string]$Path) {
        $p = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
        $p = [System.IO.Path]::GetFullPath($p)
        if ($p.Length -gt 3) { $p = $p.TrimEnd([char[]]@('\', '/')) }
        return $p
    }

    function Get-PathKey([string]$Path) {
        return ($Path -replace '/', '\').TrimEnd([char[]]@('\')).ToLowerInvariant()
    }

    function Test-SamePath([string]$Left, [string]$Right) {
        return (Test-SameText (Get-PathKey $Left) (Get-PathKey $Right))
    }

    function Test-SamePathList($LeftList, $RightList) {
        $l = @($LeftList)
        $r = @($RightList)
        if ($l.Count -ne $r.Count) { return $false }
        for ($i = 0; $i -lt $l.Count; $i++) {
            if (-not (Test-SamePath $l[$i] $r[$i])) { return $false }
        }
        return $true
    }

    # LG_CONFIG_FILE value -> entries (split on ',', trimmed, empty entries dropped).
    # Callers wrap the result in @(): a single entry would otherwise unroll to a string.
    function Split-ConfigList([string]$Value) {
        $result = New-Object System.Collections.Generic.List[string]
        if ($Value) {
            foreach ($part in $Value.Split(',')) {
                $item = $part.Trim()
                if ($item.Length -gt 0) { $result.Add($item) }
            }
        }
        return $result.ToArray()
    }

    function Test-FileExists([string]$Path) {
