# install.ps1 - VS Code "Dark Modern" theme for lazygit (Windows installer)
# https://github.com/Makihataima-Ken/lazygit-vscode-themes
#
# From a clone (Windows PowerShell 5.1 or PowerShell 7):
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -Mode Append
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -Uninstall
#
# Without a clone:
#   irm https://raw.githubusercontent.com/OWNER/lazygit-vscode-dark-modern/main/install.ps1 | iex
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/OWNER/lazygit-vscode-dark-modern/main/install.ps1))) -Mode Append
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/OWNER/lazygit-vscode-dark-modern/main/install.ps1))) -Uninstall
#
# Parameters:
#   -Mode Overlay   (default) Copy the theme to <config dir>\themes\vscode-dark-modern.yml and
#                   put it FIRST in the User environment variable LG_CONFIG_FILE, followed by
#                   your own config.yml, so your own settings win over the theme.
#   -Mode Append    Append the theme to config.yml between marker comments instead, for
#                   lazygit launched from places that do not see environment variables.
#                   Refuses (changes nothing) if config.yml already has a top-level gui: key.
#   -Uninstall      Undo both modes. config.yml itself is never deleted.
#   -ConfigDir DIR  lazygit config directory (default: output of lazygit --print-config-dir).
#   -NoPersist      Write LG_CONFIG_FILE of the current process only; nothing is written to
#                   the registry. For trying it out and for tests. Run it in the current
#                   session (.\install.ps1 -NoPersist), not with `powershell -File`.
#
# Everything runs inside one function, removed again at the end, so the script's own variables
# never reach the caller and the caller's $ErrorActionPreference is never changed. One limit:
# `irm ... | iex` runs the param() block below in the caller's scope, so variables named
# $Uninstall, $Mode, $ConfigDir or $NoPersist that already exist in that scope are reset to
# these defaults. `& ([scriptblock]::Create((irm ...)))` runs in a child scope and has no such
# effect. This script never calls `exit`.

param(
    [switch]$Uninstall,
    [ValidateSet('Overlay', 'Append')]
    [string]$Mode = 'Overlay',
    [string]$ConfigDir,
    [switch]$NoPersist
)

function Install-LazygitVSCodeDarkModern {
    param(
        [switch]$Uninstall,
        [ValidateSet('Overlay', 'Append')]
        [string]$Mode = 'Overlay',
        [string]$ConfigDir,
        [switch]$NoPersist
    )

    Set-StrictMode -Version 2.0
    $ErrorActionPreference = 'Stop'

    $ThemeId     = 'vscode-dark-modern'
    $Prefix      = '[lazygit-vscode-dark-modern]'
    $BeginMarker = '# >>> lazygit-vscode-dark-modern >>>'
    $EndMarker   = '# <<< lazygit-vscode-dark-modern <<<'
    $RepoUrl     = 'https://github.com/Makihataima-Ken/lazygit-vscode-themes'
    $InstallUrl  = 'https://raw.githubusercontent.com/OWNER/lazygit-vscode-dark-modern/main/install.ps1'
    $ShInstall   = 'curl -fsSL https://raw.githubusercontent.com/OWNER/lazygit-vscode-dark-modern/main/install.sh | sh'
    $EnvName     = 'LG_CONFIG_FILE'
    $Utf8NoBom   = New-Object System.Text.UTF8Encoding $false
    # config.yml is edited as ISO-8859-1 text: one char per byte, so every byte outside the
    # marker block (BOM, CRLF, invalid UTF-8, ...) is written back exactly as it was read.
    $Latin1      = [System.Text.Encoding]::GetEncoding(28591)
    $Latin1Bom   = [string][char]0xEF + [char]0xBB + [char]0xBF
    $Changes     = New-Object System.Collections.Generic.List[string]
    $ScriptDir   = $PSScriptRoot

    # Test seam (tests/test-install.ps1): with LGVDM_TEST_ENV_KEY set to a registry key under
    # HKCU:\Software\lgvdm-test\, the User and Machine LG_CONFIG_FILE values are read from and
    # written to its User and Machine subkeys instead of the real environment.
    $TestEnvKey  = [string]$env:LGVDM_TEST_ENV_KEY
    if ($TestEnvKey) {
        if (-not $TestEnvKey.StartsWith('HKCU:\Software\lgvdm-test\', [System.StringComparison]::OrdinalIgnoreCase) -or
            $TestEnvKey.Contains('..') -or $TestEnvKey.Contains('/')) {
            throw "$Prefix LGVDM_TEST_ENV_KEY must name a key under HKCU:\Software\lgvdm-test\ (it is only for tests). Nothing was changed."
        }
    }

# BEGIN EMBEDDED THEME (generated by tools/sync-theme.sh - do not edit by hand)
