    function Get-ThemeText([string]$Id) {
        $localTheme = ''
        if ($ScriptDir) {
            $localTheme = [System.IO.Path]::Combine([System.IO.Path]::Combine($ScriptDir, 'themes'), "$Id.yml")
        }
        if ($localTheme -and (Test-FileExists $localTheme)) {
            Write-Info "Theme source: $localTheme"
            return (ConvertTo-ThemeText ([System.IO.File]::ReadAllText($localTheme, $Utf8NoBom)))
        }
        if (-not $EmbeddedThemes.ContainsKey($Id)) { throw "$Prefix Theme '$Id' is not embedded in this installer." }
        Write-Info "Theme source: embedded copy for $Id"
        return (ConvertTo-ThemeText $EmbeddedThemes[$Id])
    }

    # Lines of a config text, each keeping its own line terminator.
    function Get-ConfigLines([string]$Text) {
        if ($Text.Length -eq 0) { return }
        foreach ($piece in [regex]::Split($Text, '(?<=\n)')) {
            if ($piece.Length -gt 0) { $piece }
        }
    }

    # Line content without terminator / trailing blanks (and without a BOM on line 1).
    function Get-LineText([string]$Line, [int]$Index) {
        $t = $Line.TrimEnd()
        if ($Index -eq 0 -and $t.StartsWith($Latin1Bom, [System.StringComparison]::Ordinal)) {
            $t = $t.Substring(3)
        }
        return $t
    }

    # Marker blocks as objects { Start; End } (line indexes, End = -1 if the end marker is missing).
    function Find-MarkerBlocks($Lines) {
        $i = 0
        while ($i -lt $Lines.Count) {
            if (Test-SameText (Get-LineText $Lines[$i] $i) $BeginMarker) {
                $j = $i + 1
                while ($j -lt $Lines.Count -and -not (Test-SameText (Get-LineText $Lines[$j] $j) $EndMarker)) { $j++ }
                if ($j -ge $Lines.Count) {
                    New-Object PSObject -Property @{ Start = $i; End = -1 }
                    return
                }
                New-Object PSObject -Property @{ Start = $i; End = $j }
                $i = $j + 1
            } else {
                $i++
            }
        }
    }

    function Get-BlockLineSet($Blocks) {
        $set = @{}
        foreach ($b in @($Blocks)) {
            for ($k = $b.Start; $k -le $b.End; $k++) { $set[$k] = $true }
        }
        return $set
    }

    # Text with every marker block removed; $Replacement goes where the first block was.
    function Join-WithoutBlocks($Lines, $Blocks, [string]$Replacement) {
        $skip = Get-BlockLineSet $Blocks
        $sb = New-Object System.Text.StringBuilder
        $inserted = $false
        for ($i = 0; $i -lt $Lines.Count; $i++) {
            if ($skip.ContainsKey($i)) {
                if (-not $inserted) {
                    [void]$sb.Append($Replacement)
                    $inserted = $true
                }
                continue
            }
            [void]$sb.Append($Lines[$i])
        }
        return $sb.ToString()
    }

    function Test-TopLevelGui($Lines, $Blocks) {
        $skip = Get-BlockLineSet $Blocks
        for ($i = 0; $i -lt $Lines.Count; $i++) {
            if ($skip.ContainsKey($i)) { continue }
            if ((Get-LineText $Lines[$i] $i) -cmatch '^(gui|"gui"|''gui'')\s*:') { return $true }
        }
        return $false
    }

    # True if a `theme:` key appears inside a top-level `gui:` mapping.
    function Test-GuiThemeKey($Lines) {
        $inGui = $false
        for ($i = 0; $i -lt $Lines.Count; $i++) {
            $line = Get-LineText $Lines[$i] $i
            if ($line -cmatch '^(gui|"gui"|''gui'')\s*:') { $inGui = $true; continue }
            if ($line -cmatch '^[^\s#]') { $inGui = $false; continue }
            if ($inGui -and $line -cmatch '^\s+(theme|"theme"|''theme'')\s*:') { return $true }
        }
        return $false
    }

    function Backup-ConfigFile {
        $bak = $ConfigFile + '.bak'
        [System.IO.File]::Copy($ConfigFile, $bak, $true)
        # Copy keeps a read-only attribute, which would block the next backup.
        $attrs = [System.IO.File]::GetAttributes($bak)
        if (($attrs -band [System.IO.FileAttributes]::ReadOnly) -ne 0) {
            [System.IO.File]::SetAttributes($bak, ($attrs -band (-bnot [System.IO.FileAttributes]::ReadOnly)))
        }
        Add-Change "Backed up the previous $ConfigFile to $bak"
    }

