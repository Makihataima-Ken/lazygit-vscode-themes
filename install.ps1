    function Write-Info([string]$Message) { Write-Host "$Prefix $Message" }

    function Write-Warn([string]$Message) { Write-Warning "$Prefix $Message" }

    function Add-Change([string]$Message) { $Changes.Add($Message) }

    function Test-SameText([string]$Left, [string]$Right) {
        return [string]::Equals($Left, $Right, [System.StringComparison]::Ordinal)
    }

    function Test-IsWindowsHost {
        if ($PSVersionTable.PSEdition -eq 'Desktop') { return $true }
        $isWin = Get-Variable -Name IsWindows -ValueOnly -ErrorAction SilentlyContinue
        if ($null -eq $isWin) { return $true }
        return [bool]$isWin
