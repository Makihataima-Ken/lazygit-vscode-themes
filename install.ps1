    function Invoke-AppendInstall {
        $themeText = Get-ThemeText $ThemeId
        [void][System.IO.Directory]::CreateDirectory($TargetDir)
        $blockText = $Latin1.GetString($Utf8NoBom.GetBytes($BeginMarker + "`n" + $themeText + $EndMarker + "`n"))

        $exists = Test-FileExists $ConfigFile
        $oldText = ''
        if ($exists) { $oldText = Read-ConfigText $ConfigFile }
        $wide = Get-WideEncodingName $oldText
        if ($wide) {
            throw ("$Prefix Append mode refused: $ConfigFile is saved as $wide (Windows PowerShell's > and Out-File write UTF-16), and the theme block is UTF-8, so appending would break it. Nothing was changed. " +
                "Either use overlay mode (run this installer without -Mode Append), or re-save config.yml as UTF-8 and run again.")
        }
        $lines = @(Get-ConfigLines $oldText)
        $blocks = @(Find-MarkerBlocks $lines)
        $broken = @($blocks | Where-Object { $_.End -lt 0 })
        if ($broken.Count -gt 0) {
            throw "$Prefix $ConfigFile has a '$BeginMarker' line (line $($broken[0].Start + 1)) without a matching '$EndMarker' line. Fix or remove it by hand, then run again. Nothing was changed."
        }

        if ($blocks.Count -gt 0) {
            $newText = Join-WithoutBlocks $lines $blocks $blockText
            $action = 'Replaced the theme block in'
            if (Test-TopLevelGui $lines $blocks) {
                Write-Warn "$ConfigFile has another top-level gui: key outside the theme block; lazygit refuses to start with two gui: keys. Merge them, or switch to overlay mode (run with -Uninstall, then install without -Mode Append)."
            }
        } elseif (Test-TopLevelGui $lines $blocks) {
            throw ("$Prefix Append mode refused: $ConfigFile already has a top-level gui: key, and a second one would stop lazygit from starting. Nothing was changed. " +
                "Either use overlay mode (run this installer without -Mode Append), or paste the theme's theme: block (and border: single) under your existing gui: key by hand: $RepoUrl/blob/main/themes/$ThemeId.yml")
        } else {
            $newText = $oldText
            if ($newText.Length -gt 0 -and -not $newText.EndsWith("`n", [System.StringComparison]::Ordinal)) {
                if ($newText.Contains("`r`n")) { $newText += "`r`n" } else { $newText += "`n" }
            }
            $newText += $blockText
            $action = 'Appended the theme block to'
        }

        if (Test-SameText $newText $oldText) {
            Write-Info "The theme block in $ConfigFile is already up to date."
        } else {
            if ($exists -and $oldText.Length -gt 0) { Backup-ConfigFile }
            Write-ConfigText $ConfigFile $newText
            Add-Change "$action $ConfigFile (between the '$BeginMarker' and '$EndMarker' lines)"
        }

        # lazygit only reads config.yml when LG_CONFIG_FILE is unset or lists it.
        if ($NoPersist) {
            $effective = [string]$env:LG_CONFIG_FILE
        } else {
            $effective = Get-StoredValue 'User'
            if (@(Split-ConfigList $effective).Count -eq 0) {
                $effective = Get-StoredValue 'Machine'
            }
        }
        $effectiveEntries = @(Split-ConfigList $effective)
        if ($effectiveEntries.Count -gt 0 -and @($effectiveEntries | Where-Object { Test-SamePath $_ $ConfigFile }).Count -eq 0) {
            Write-Warn "LG_CONFIG_FILE is set to $effective and does not list $ConfigFile, so lazygit will not read the theme block. Add $ConfigFile to LG_CONFIG_FILE or use overlay mode."
        }

        $notes = @()
        $notes += "To undo: $(Get-UndoCommand)"
        $notes += 'Next: restart lazygit.'
        $notes += "For matching colors, import extras/windows-terminal/$ThemeId.json ($RepoUrl/tree/main/extras/windows-terminal) in your terminal."
        Write-Summary $notes
    }

    # ---------------------------------------------------------------- uninstall

    # Order: LG_CONFIG_FILE first, then config.yml, the theme file last. If a step fails, no
    # LG_CONFIG_FILE is left listing a theme file that is already gone.
    function Invoke-Uninstall {
        $processValue = [string]$env:LG_CONFIG_FILE
        $processNew = Get-UninstallValue $processValue ''
        # Read even with -NoPersist: a value this run leaves alone must not lose its theme file.
        $user = Get-StoredValue 'User'
        $machine = Get-StoredValue 'Machine'
        if (-not $NoPersist) {
            $userNew = Get-UninstallValue $user $machine
            if ($null -ne $userNew) {
                if ($userNew -eq '') {
                    Remove-UserVariable
                    Add-Change "Deleted the User environment variable LG_CONFIG_FILE (was: $user)"
                } else {
                    Set-UserValue $userNew
                    Add-Change "Set the User environment variable LG_CONFIG_FILE = $userNew (theme entry removed)"
                }
            }
        }
        if ($null -ne $processNew) {
            if ($processNew -eq '') {
                Remove-Item -LiteralPath 'Env:LG_CONFIG_FILE' -ErrorAction SilentlyContinue
                if ($NoPersist) { Add-Change 'Removed LG_CONFIG_FILE from this PowerShell process (-NoPersist)' }
            } else {
                $env:LG_CONFIG_FILE = $processNew
                if ($NoPersist) { Add-Change "Set LG_CONFIG_FILE for this PowerShell process only (-NoPersist): $processNew" }
            }
        }

        if (Test-FileExists $ConfigFile) {
            $oldText = Read-ConfigText $ConfigFile
            $wide = Get-WideEncodingName $oldText
            if ($wide) {
                if ($oldText.Contains($BeginMarker) -or (Read-ConfigScanText $ConfigFile).Contains($BeginMarker)) {
                    Write-Warn "$ConfigFile is saved as $wide and contains a '$BeginMarker' line; left unchanged, since editing it byte-wise would break it. Remove the theme block by hand."
                }
            } else {
                $lines = @(Get-ConfigLines $oldText)
                $blocks = @(Find-MarkerBlocks $lines)
                $broken = @($blocks | Where-Object { $_.End -lt 0 })
                if ($broken.Count -gt 0) {
                    Write-Warn "$ConfigFile has a '$BeginMarker' line (line $($broken[0].Start + 1)) without a matching '$EndMarker' line; left unchanged. Remove the theme block by hand."
                } elseif ($blocks.Count -gt 0) {
                    Backup-ConfigFile
                    Write-ConfigText $ConfigFile (Join-WithoutBlocks $lines $blocks '')
                    Add-Change "Removed the theme block from $ConfigFile"
                }
            }
        }

        # lazygit refuses to start while a listed file is missing: keep the theme file while an
        # LG_CONFIG_FILE this run does not change still lists it.
        $keepTheme = $false
        if ($NoPersist -and (Test-ListsCatalogTheme $user)) {
            $keepTheme = $true
            Write-Warn 'The User environment variable LG_CONFIG_FILE still lists a catalog theme, and -NoPersist leaves it alone, so catalog theme files were kept. To remove them, run again without -NoPersist.'
        }
        if (Test-ListsCatalogTheme $machine) {
            $keepTheme = $true
            Write-Warn 'The Machine-wide LG_CONFIG_FILE lists a catalog theme, so catalog theme files were kept. Remove that entry from an elevated prompt, then run -Uninstall again.'
        }
        if (-not $keepTheme) {
            foreach ($id in @(Get-ManagedThemeIds)) {
                $dest = Get-ThemeDestination $id
                if (-not (Test-FileExists $dest)) { continue }
                $expected = [Convert]::ToBase64String($Utf8NoBom.GetBytes((Get-ThemeText $id)))
                $actual = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($dest))
                if (Test-SameText $actual $expected) {
                    Remove-Item -LiteralPath $dest -Force
                    Add-Change "Removed managed theme $dest"
                } else {
                    Write-Warn "Kept modified or older managed theme $dest. It is no longer tracked; remove it manually if you no longer need it."
                }
            }
            if (Test-FileExists $ManagedFile) {
                Remove-Item -LiteralPath $ManagedFile -Force
                Add-Change "Removed installer manifest $ManagedFile"
            }
            if (Test-Path -LiteralPath $ThemesDir -PathType Container) {
                if (@(Get-ChildItem -LiteralPath $ThemesDir -Force).Count -eq 0) {
                    Remove-Item -LiteralPath $ThemesDir -Force
                    Add-Change "Removed the empty directory $ThemesDir"
                }
            }
        }

        $notes = @()
        if (Test-FileExists $ConfigFile) { $notes += "Kept $ConfigFile (your settings are never deleted)." }
        if (-not $NoPersist) {
            $notes += 'Next: open a NEW terminal (running programs keep the old environment), then restart lazygit.'
        }
        Write-Summary $notes
    }

    # ---------------------------------------------------------------- main

    if (-not (Test-IsWindowsHost)) {
        Write-Host "$Prefix This is the Windows installer. On macOS/Linux use install.sh instead:"
        Write-Host "  $ShInstall"
        return
    }

    # Harmless here; keeps any future download on TLS 1.2 in Windows PowerShell 5.1.
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    } catch { }

    $ThemeCatalog = @(Get-ThemeCatalog)
    if ($ListThemes) {
        if ($Uninstall -or $Mode -eq 'Append') { throw "$Prefix -ListThemes cannot be combined with -Uninstall or -Mode Append." }
        Write-Host "$Prefix Available themes:"
        foreach ($entry in $ThemeCatalog) { Write-Host ("  {0,-24} {1}" -f $entry.Id, $entry.Name) }
        return
    }
    $selected = @($ThemeCatalog | Where-Object { $_.Id -eq $Theme })
    if ($selected.Count -ne 1) {
        $choices = ($ThemeCatalog | ForEach-Object { $_.Id }) -join ', '
        throw "$Prefix Unknown theme '$Theme'. Run -ListThemes to see: $choices"
    }
    $ThemeId = $selected[0].Id

    if ($ConfigDir) {
        $rawDir = $ConfigDir
        $dirSource = '-ConfigDir'
    } else {
        $rawDir = Get-LazygitConfigDir
        $dirSource = 'lazygit --print-config-dir'
        if (-not $rawDir) {
            $rawDir = Get-DefaultConfigDir
            if ($env:CONFIG_DIR) { $dirSource = 'CONFIG_DIR' } else { $dirSource = "lazygit's default lookup" }
            if (Get-Command -Name 'lazygit' -CommandType Application -ErrorAction SilentlyContinue) {
                Write-Warn "lazygit --print-config-dir gave no usable answer, so the config directory was worked out the way lazygit does it: $rawDir. If lazygit uses another one, run again with -ConfigDir <dir>."
            } else {
                Write-Warn "lazygit is not on PATH (just installed it? open a new terminal), so the config directory was worked out the way lazygit does it: $rawDir. If lazygit uses another one, run again with -ConfigDir <dir>."
            }
        }
    }
    $TargetDir  = Resolve-FullPath $rawDir
    $ConfigFile = [System.IO.Path]::Combine($TargetDir, 'config.yml')
    $ThemesDir  = [System.IO.Path]::Combine($TargetDir, 'themes')
    $ThemeDest  = [System.IO.Path]::Combine($ThemesDir, "$ThemeId.yml")
    $ManagedFile = [System.IO.Path]::Combine($ThemesDir, '.lazygit-vscode-themes-managed')

    Write-Info "lazygit config directory: $TargetDir (from $dirSource)"
    Write-Info "selected theme: $ThemeId ($(Get-ThemeTitle $ThemeId))"
    if ($TestEnvKey) { Write-Info "Test mode: the User/Machine LG_CONFIG_FILE values are kept under $TestEnvKey (LGVDM_TEST_ENV_KEY)." }

    if ($Uninstall) {
        Invoke-Uninstall
    } elseif ($Mode -eq 'Append') {
        Invoke-AppendInstall
    } else {
        Invoke-OverlayInstall
    }
}

try {
    Install-LazygitVSCodeThemes -Uninstall:$Uninstall -Mode $Mode -ConfigDir $ConfigDir -NoPersist:$NoPersist -Theme $Theme -ListThemes:$ListThemes
} finally {
    Remove-Item -LiteralPath 'Function:\Install-LazygitVSCodeThemes' -ErrorAction SilentlyContinue
}
