        # Pre-catalog releases installed only this file and had no manifest. It is safe to
        # adopt if it still identifies this repository; unrelated theme files are never adopted.
        $legacy = Get-ThemeDestination $DefaultThemeId
        if ($ids.Count -eq 0 -and (Test-FileExists $legacy) -and
            ([System.IO.File]::ReadAllText($legacy, $Utf8NoBom).Contains('lazygit-vscode-themes'))) {
            $ids.Add($DefaultThemeId)
        }
        return $ids.ToArray()
    }

