# install.ps1 - VS Code-inspired themes for lazygit (Windows installer)
# https://github.com/Makihataima-Ken/lazygit-vscode-themes
#
# From a clone (Windows PowerShell 5.1 or PowerShell 7):
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -Mode Append
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -Uninstall
#
# Without a clone:
#   irm https://raw.githubusercontent.com/Makihataima-Ken/lazygit-vscode-themes/main/install.ps1 | iex
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/Makihataima-Ken/lazygit-vscode-themes/main/install.ps1))) -Theme vscode-light-modern
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/Makihataima-Ken/lazygit-vscode-themes/main/install.ps1))) -Uninstall
#
# Parameters:
#   -Theme ID       Select a catalog theme (default: vscode-dark-modern).
#   -ListThemes     Print the catalog and make no changes.
#   -Mode Overlay   (default) Copy every catalog theme to <config dir>\themes\ and put the
#                   selected one FIRST in the User environment variable LG_CONFIG_FILE, followed by
#                   your own config.yml, so your own settings win over the theme.
#   -Mode Append    Append the theme to config.yml between marker comments instead, for
#                   lazygit launched from places that do not see environment variables.
#                   Refuses (changes nothing) if config.yml already has a top-level gui: key.
#   -Uninstall      Undo both modes. config.yml itself is never deleted.
#   -ConfigDir DIR  lazygit config directory (default: output of lazygit --print-config-dir).
#   -NoPersist      Write LG_CONFIG_FILE of the current process only; nothing is written to
#                   the registry. For trying it out and for tests. Run it in the current
#                   session (.\install.ps1 -NoPersist), not with `powershell -File`.
#
# Everything runs inside one function, removed again at the end, so the script's own variables
# never reach the caller and the caller's $ErrorActionPreference is never changed. One limit:
# `irm ... | iex` runs the param() block below in the caller's scope, so variables named
# $Uninstall, $Mode, $ConfigDir or $NoPersist that already exist in that scope are reset to
# these defaults. `& ([scriptblock]::Create((irm ...)))` runs in a child scope and has no such
# effect. This script never calls `exit`.

param(
    [switch]$Uninstall,
    [ValidateSet('Overlay', 'Append')]
    [string]$Mode = 'Overlay',
    [string]$ConfigDir,
    [switch]$NoPersist,
    [string]$Theme = 'vscode-dark-modern',
    [switch]$ListThemes
)

