    function Get-ManagedThemeIds {
        $ids = New-Object System.Collections.Generic.List[string]
        if (Test-FileExists $ManagedFile) {
            foreach ($raw in [System.IO.File]::ReadAllLines($ManagedFile, $Utf8NoBom)) {
                $id = $raw.Trim()
                if ($id -and @($ThemeCatalog | Where-Object { $_.Id -eq $id }).Count -eq 1) { $ids.Add($id) }
